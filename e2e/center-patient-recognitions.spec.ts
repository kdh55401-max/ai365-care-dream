import { expect, test } from '@playwright/test'
async function open(page: import('@playwright/test').Page) {
  await page.getByRole('navigation', { name: '센터 업무 메뉴' }).getByRole('button', { name: '수급자관리' }).click()
  await page.getByRole('button', { name: '가상 수급자', exact: true }).click()
  await page.getByRole('tab', { name: '등급·인정이력', exact: true }).click()
  return page.getByRole('region', { name: '수급자 등급 인정이력' })
}
test('인정이력 저장과 적용 분리·번호0보존·갱신/보관·재진입', async ({ page }) => {
  await page.goto('/center?demo=1')
  await page.evaluate(() => { localStorage.setItem('gadream365:center-operations:demo:v1', JSON.stringify({ people: [{ id: '00000000-0000-4000-8000-000000000091', kind: 'patient', name: '가상 수급자', status: '수급중', category: '기존 등급', start: '2026-01-02', end: '2026-12-31', examination: '', notes: {}, version: 1, archived: false }], visits: [], requests: {} })) })
  await page.reload(); let section = await open(page)
  async function add(grade: string, sequence: string, note: string) {
    await section.getByRole('button', { name: '인정이력 추가', exact: true }).click()
    await section.getByLabel('인정서 등급', { exact: true }).fill(grade)
    await section.getByLabel('장기요양 인정번호', { exact: true }).fill('L000123')
    await section.getByLabel('인정번호 확장값', { exact: true }).fill(sequence)
    await section.getByLabel('인정기간 시작일', { exact: true }).fill('2026-10-01')
    await section.getByLabel('인정기간 종료일', { exact: true }).fill('2027-09-30')
    await section.getByLabel('인정이력 비고', { exact: true }).fill(note)
    await section.getByRole('button', { name: '인정이력 저장', exact: true }).click()
    await expect(section).toContainText('현재 기본정보는 바뀌지 않았습니다.')
  }
  await add('3등급', '001', '최초인정')
  await expect(section).toContainText('현재 기본정보 등급: 기존 등급')
  let first = section.getByRole('row').filter({ hasText: '최초인정' })
  await expect(first).toContainText('L000123-001')
  await first.getByRole('button', { name: '등급 정보에 적용', exact: true }).click()
  await section.getByRole('button', { name: '변경 확인', exact: true }).click()
  await expect(section).toContainText('현재 기본정보 등급: 3등급')
  await expect(first.getByRole('button', { name: '인정이력 보관', exact: true })).toBeDisabled()
  await add('2등급', '002', '갱신인정')
  await section.getByRole('row').filter({ hasText: '갱신인정' }).getByRole('button', { name: '등급 정보에 적용', exact: true }).click()
  await section.getByRole('button', { name: '변경 확인', exact: true }).click()
  await expect(section).toContainText('현재 기본정보 등급: 2등급')
  await first.getByRole('button', { name: '인정이력 보관', exact: true }).click()
  await section.getByRole('button', { name: '변경 확인', exact: true }).click()
  await expect(first).toHaveCount(0)
  await page.reload(); section = await open(page)
  await expect(section).toContainText('마지막 적용 인정정보: 2등급 · L000123-002')
  await section.getByRole('checkbox', { name: '보관된 인정이력 보기' }).check()
  first = section.getByRole('row').filter({ hasText: '최초인정' }); await expect(first).toContainText('보관')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('gadream365:center-operations:demo:v1')!).people[0])
  expect(saved).toMatchObject({ category: '2등급', start: '2026-01-02', end: '2026-12-31' })
})
