test('양식 전환 취소는 미저장 본문·원문 보존, 동의한 전환만 초기화', async ({ page }) => {
 await bundledDemo(page); await page.goto('/center?demo=1')
 await page.getByRole('navigation', { name: '센터 업무 메뉴' }).getByRole('button', { name: '서류함', exact: true }).click()
 await page.getByRole('button', { name: '+ 문서 작성', exact: true }).click()
 const template = page.getByLabel('문서 양식', { exact: true })
 await page.getByLabel('문서 본문', { exact: true }).fill('보존할 가상 사례 초안')
 const dialogs: string[] = []
 const dismiss = async (dialog: import('@playwright/test').Dialog) => { dialogs.push(dialog.message()); await dialog.dismiss() }
 page.on('dialog', dismiss)
 await template.selectOption('state-change-record')
 await expect(template).toHaveValue('case-management')
 await expect(page.getByLabel('문서 본문', { exact: true })).toHaveValue('보존할 가상 사례 초안')
 expect(dialogs).toHaveLength(1)
 page.off('dialog', dismiss)
 page.once('dialog', async dialog => { await dialog.accept() })
 await template.selectOption('state-change-record')
 await expect(page.getByLabel('1주차 특이사항 및 조치내용', { exact: true })).toBeEmpty()
 await page.getByLabel('작성틀 원문', { exact: true }).fill('보존할 가상 관찰 원문')
 page.on('dialog', dismiss)
 await template.selectOption('case-management')
 await expect(template).toHaveValue('state-change-record')
 await expect(page.getByLabel('작성틀 원문', { exact: true })).toHaveValue('보존할 가상 관찰 원문')
 page.off('dialog', dismiss)
 page.once('dialog', async dialog => { await dialog.accept() })
 await template.selectOption('case-management')
 await expect(page.getByLabel('문서 본문', { exact: true })).toBeEmpty()
 // Returning without input needs no discard confirmation and cannot resurrect an older source.
 await template.selectOption('state-change-record')
 await expect(page.getByLabel('작성틀 원문', { exact: true })).toBeEmpty()
})
