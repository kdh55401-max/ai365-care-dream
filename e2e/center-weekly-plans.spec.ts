import { expect, test } from '@playwright/test'
const patientId = '00000000-0000-4000-8000-000000000051', workerId = '00000000-0000-4000-8000-000000000052'
async function open(page: import('@playwright/test').Page) {
  await page.getByRole('navigation', { name: '센터 업무 메뉴' }).getByRole('button', { name: '수급자관리' }).click()
  await page.getByRole('button', { name: '가상 수급자', exact: true }).click()
  await page.getByRole('tab', { name: '급여계획', exact: true }).click()
  return page.getByRole('region', { name: '주간 급여계획' })
}
test('주간 계획과 방문 항목 저장·월 예상 일정·겹침 입력 유지·재진입', async ({ page }) => {
  await page.goto('/center?demo=1')
  await page.evaluate(({ patientId, workerId }) => {
    const base = { status: '', category: '', start: '', end: '', examination: '', notes: {}, version: 1 }
    localStorage.setItem('gadream365:center-operations:demo:v1', JSON.stringify({ people: [{ ...base, id: patientId, kind: 'patient', name: '가상 수급자' }, { ...base, id: workerId, kind: 'worker', name: '가상 직원' }], visits: [], requests: {} }))
  }, { patientId, workerId })
  await page.reload(); let section = await open(page)
  await section.getByRole('button', { name: '새 주간 계획', exact: true }).click()
  await section.getByLabel('적용월', { exact: true }).fill('2026-10')
  await section.getByLabel('계획 참고사항', { exact: true }).fill('가상 계획')
  await section.getByRole('button', { name: '계획 정보 저장', exact: true }).click()
  await expect(section).toContainText('저장 버전 1')
  await section.getByRole('button', { name: '방문 항목 추가', exact: true }).click()
  await section.getByRole('combobox', { name: '제공자 1', exact: true }).selectOption(workerId)
  await section.getByRole('button', { name: '방문 항목 저장', exact: true }).click()
  await expect(section).toContainText('저장 버전 2')
  await expect(section).toContainText('4건 · 계획 기준 예상 내역')
  await section.getByRole('button', { name: '방문 항목 추가', exact: true }).click()
  await section.getByRole('combobox', { name: '제공자 1', exact: true }).selectOption(workerId)
  await section.getByRole('button', { name: '방문 항목 저장', exact: true }).click()
  await expect(section.getByRole('alert')).toContainText('겹치는')
  await expect(section.getByLabel('시작 시간', { exact: true })).toHaveValue('09:00')
  await section.getByRole('button', { name: '취소', exact: true }).click()
  await page.reload(); section = await open(page)
  await expect(section).toContainText('가상 계획')
  await expect(section).toContainText('저장 버전 2')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('gadream365:center-operations:demo:v1')!).visits)).toEqual([])
  await section.getByRole('button', { name: '월 일정 반영 내역 확인', exact: true }).click()
  await expect(section).toContainText('신규 4건 · 유지 0건 · 겹침 0건')
  await section.getByRole('button', { name: '확인한 계획을 방문일정에 반영', exact: true }).click()
  await expect(section).toContainText('방문일정 4건 생성')
  await section.getByRole('button', { name: '월 일정 반영 내역 확인', exact: true }).click()
  await expect(section).toContainText('신규 0건 · 유지 4건 · 겹침 0건')
  await section.getByRole('button', { name: '확인한 계획을 방문일정에 반영', exact: true }).click()
  await expect(section).toContainText('방문일정 0건 생성')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('gadream365:center-operations:demo:v1')!).visits.length)).toBe(4)
})
