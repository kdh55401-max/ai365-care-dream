import { expect, test } from '@playwright/test'

test('센터 문서 저장·재진입·결과평가 현황·명시 확정을 연결한다', async ({ page }) => {
  await page.goto('/center?demo=1')
  const navigation = page.getByRole('navigation', { name: '센터 업무 메뉴' })
  await navigation.getByRole('button', { name: '서류함' }).click()
  await page.getByRole('button', { name: '+ 문서 작성' }).click()
  await page.getByLabel('문서 제목', { exact: true }).fill('가상 사례관리 검증')
  await page.getByLabel('문서 기준월', { exact: true }).fill('2026-07')
  await page.getByLabel('문서 본문', { exact: true }).fill('기술 시험용 가상 기록. 실제 기관 자료가 아닙니다.')
  await page.getByRole('button', { name: '초안 저장', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('초안을 저장했습니다')
  await page.reload()
  await navigation.getByRole('button', { name: '서류함' }).click()
  await page.getByRole('button', { name: '가상 사례관리 검증', exact: true }).click()
  await expect(page.getByRole('region', { name: '문서 상세' })).toContainText('v1')
  await navigation.getByRole('button', { name: '기관평가' }).click()
  await page.getByLabel('평가 조회 연도').fill('2026')
  const caseRow = page.locator('.cd-evaluation-row').filter({ has: page.getByRole('heading', { name: '사례관리 + 평가기록지', exact: true }) })
  await expect(caseRow.getByRole('button').filter({ hasText: '2반기' })).toContainText('미작성')
  await navigation.getByRole('button', { name: '서류함' }).click()
  await page.getByRole('button', { name: '가상 사례관리 검증', exact: true }).click()
  await page.getByRole('button', { name: '초안 수정', exact: true }).click()
  await page.getByLabel('결과평가 내용을 작성했습니다').check()
  await page.getByRole('button', { name: '초안 저장', exact: true }).click()
  await page.getByRole('button', { name: '확정 검토', exact: true }).click()
  await expect(page.getByRole('region', { name: '문서 확정 확인' })).toContainText('v2')
  await page.getByRole('button', { name: '내용 확인 후 확정', exact: true }).click()
  await expect(page.getByRole('region', { name: '문서 상세' })).toContainText('확정 · v3')
  await expect(page.getByRole('button', { name: '초안 수정', exact: true })).toHaveCount(0)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '내용 내려받기 (.txt)', exact: true }).click()
  expect((await download).suggestedFilename()).toMatch(/-v3\.txt$/)
  await navigation.getByRole('button', { name: '기관평가' }).click()
  await expect(caseRow.getByRole('button').filter({ hasText: '2반기' })).toContainText('1건')
  for (const name of ['서류함(평가서류 작성)', '의무교육 수료 현황', '평가매뉴얼&자가진단']) {
    await page.getByRole('tab', { name, exact: true }).click()
    await expect(page.getByRole('tabpanel')).toBeVisible()
  }
})
