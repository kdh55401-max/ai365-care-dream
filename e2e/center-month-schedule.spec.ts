import { expect, test } from '@playwright/test'
test('월 검토 후 변경 감지·잠금·수정 거절·해제 후 수정', async ({ page }) => {
  const workerId = '00000000-0000-4000-8000-000000000071', patientId = '00000000-0000-4000-8000-000000000072', visitId = '00000000-0000-4000-8000-000000000073'
  await page.goto('/center?demo=1')
  await page.evaluate(({ workerId, patientId, visitId }) => {
    const base = { status: '', category: '', start: '', end: '', examination: '', notes: {}, version: 1 }
    localStorage.setItem('gadream365:center-operations:demo:v1', JSON.stringify({ people: [{ ...base, id: workerId, kind: 'worker', name: '가상 직원' }, { ...base, id: patientId, kind: 'patient', name: '가상 수급자' }], visits: [{ id: visitId, workerId, patientId, date: '2026-10-22', time: '09:00', minutes: 60, service: '요양', version: 1 }], requests: {} }))
  }, { workerId, patientId, visitId })
  await page.reload()
  await page.getByRole('navigation', { name: '센터 업무 메뉴' }).getByRole('button', { name: '방문일정' }).click()
  await page.getByLabel('일정 년월').fill('2026-10')
  const section = page.getByRole('region', { name: '센터 월 일정 검토' })
  await section.getByRole('button', { name: '월 일정 검토 새로 조회' }).click()
  await expect(section).toContainText('관련 일정 1건')
  await page.evaluate(() => { const key = 'gadream365:center-operations:demo:v1', value = JSON.parse(localStorage.getItem(key)!); value.visits[0].version++; localStorage.setItem(key, JSON.stringify(value)) })
  await section.getByRole('button', { name: '센터 일정 잠금 검토', exact: true }).click()
  await section.getByRole('checkbox').check()
  await section.getByRole('button', { name: '확인 후 센터 잠금', exact: true }).click()
  await expect(section.getByRole('alert')).toContainText('바뀌었습니다')
  await section.getByRole('button', { name: '월 일정 검토 새로 조회' }).click()
  await section.getByRole('button', { name: '센터 일정 잠금 검토', exact: true }).click()
  await section.getByRole('checkbox').check()
  await section.getByRole('button', { name: '확인 후 센터 잠금', exact: true }).click()
  await expect(section).toContainText('센터 잠금됨')
  await page.getByRole('button', { name: /2026-10-22 09:00.*방문일정 수정/ }).click()
  const dialog = page.getByRole('dialog', { name: '방문일정 수정' })
  await dialog.getByLabel('방문시간').fill('10:00')
  await dialog.getByRole('button', { name: '시연 세션에 반영' }).click()
  await expect(dialog.getByRole('alert')).toContainText('잠긴 월')
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  await section.getByRole('button', { name: '센터 잠금 해제 검토' }).click()
  await section.getByRole('checkbox').check()
  await section.getByLabel('해제 확인 문구').fill('잠금해제')
  await section.getByRole('button', { name: '확인 후 잠금 해제', exact: true }).click()
  await expect(section).toContainText('편집 가능')
  await page.getByRole('button', { name: /2026-10-22 09:00.*방문일정 수정/ }).click()
  await dialog.getByLabel('방문시간').fill('10:00')
  await dialog.getByRole('button', { name: '시연 세션에 반영' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: /2026-10-22 10:00.*방문일정 수정/ })).toBeVisible()
})
