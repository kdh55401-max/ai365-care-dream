import { expect, test } from '@playwright/test'
async function open(page: import('@playwright/test').Page) {
  await page.getByRole('navigation', { name: '센터 업무 메뉴' }).getByRole('button', { name: '수급자관리' }).click()
  await page.getByRole('button', { name: '가상 수급자', exact: true }).click()
  await page.getByRole('tab', { name: '계약이력', exact: true }).click()
  return page.getByRole('region', { name: '수급자 계약기간 이력' })
}
test('계약 저장과 적용 분리·갱신 적용·이전 이력 보관·재진입', async ({ page }) => {
  await page.goto('/center?demo=1')
  await page.evaluate(() => { localStorage.setItem('gadream365:center-operations:demo:v1', JSON.stringify({ people: [{ id: '00000000-0000-4000-8000-000000000081', kind: 'patient', name: '가상 수급자', status: '수급중', category: '', start: '', end: '', examination: '', notes: {}, version: 1, archived: false }], visits: [], requests: {} })) })
  await page.reload(); let section = await open(page)
  async function add(note: string, end: string) {
    await section.getByRole('button', { name: '계약이력 추가', exact: true }).click()
    await section.getByLabel('이력 계약일', { exact: true }).fill('2026-10-01')
    await section.getByLabel('계약기간 시작일', { exact: true }).fill('2026-10-03')
    await section.getByLabel('계약기간 종료일', { exact: true }).fill(end)
    await section.getByLabel('계약 비고', { exact: true }).fill(note)
    await section.getByRole('button', { name: '계약이력 저장', exact: true }).click()
    await expect(section).toContainText('현재 기본정보는 바뀌지 않았습니다.')
  }
  await add('최초계약', '2027-10-02')
  await expect(section).toContainText('현재 기본정보: 계약일 미입력 · 만료일 미입력')
  let first = section.getByRole('row').filter({ hasText: '최초계약' })
  await first.getByRole('button', { name: '현재 정보에 적용', exact: true }).click()
  await section.getByRole('button', { name: '변경 확인', exact: true }).click()
  await expect(section).toContainText('현재 기본정보: 계약일 2026-10-01 · 만료일 2027-10-02')
  await expect(first.getByRole('button', { name: '이력 수정', exact: true })).toBeDisabled()
  await expect(first.getByRole('button', { name: '이력 보관', exact: true })).toBeDisabled()
  await add('갱신계약', '2028-10-02')
  await section.getByRole('row').filter({ hasText: '갱신계약' }).getByRole('button', { name: '현재 정보에 적용', exact: true }).click()
  await section.getByRole('button', { name: '변경 확인', exact: true }).click()
  await expect(section).toContainText('현재 기본정보: 계약일 2026-10-01 · 만료일 2028-10-02')
  await first.getByRole('button', { name: '이력 보관', exact: true }).click()
  await section.getByRole('button', { name: '변경 확인', exact: true }).click()
  await expect(first).toHaveCount(0)
  await page.reload(); section = await open(page)
  await expect(section).toContainText('만료일 2028-10-02')
  await section.getByRole('checkbox', { name: '보관된 계약이력 보기' }).check()
  first = section.getByRole('row').filter({ hasText: '최초계약' }); await expect(first).toContainText('보관')
  await expect(first.getByRole('button', { name: '현재 정보에 적용', exact: true })).toBeDisabled()
})
