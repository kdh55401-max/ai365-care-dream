/** 요양보호사의 발화가 오늘 돌봄 대상 어르신과 무관한 잡담(날씨/뉴스/스포츠 등)인지
 * 감지하는 규칙 기반 판정기. 돌봄 관련 단서 키워드가 하나라도 있으면 절대 무관한
 * 발화로 보지 않는다(오탐으로 실제 돌봄 이야기를 막지 않기 위한 보수적 설계) — 반대로
 * 돌봄 단서가 전혀 없고, 명백히 무관한 화제 단서가 있을 때만 무관한 발화로 판정한다.
 * 애매한 입력(짧은 답, 돌봄 단서도 무관 단서도 없는 문장)은 무관하다고 단정하지
 * 않고 그대로 AI에게 넘긴다 — "특이사항 없어요", "잘 모르겠어요" 같은 정상 응답을
 * 잡담으로 오분류하지 않기 위함이다. */

const CARE_KEYWORDS = [
  '어르신', '식사', '드시', '드셨', '드신', '드셔', '식욕', '수분', '물', '음식', '반찬', '밥',
  '약', '복약', '투약', '화장실', '대변', '소변', '기저귀', '배설', '목욕', '샤워', '위생', '욕창',
  '이동', '걷', '걸음', '보행', '휘청', '낙상', '넘어지', '넘어질', '넘어졌', '휠체어', '부축',
  '통증', '아프', '아팠', '호흡', '숨', '기침', '열', '체온', '혈압', '혈당',
  '수면', '잠', '주무', '잠들',
  '대화', '말씀', '인지', '기억', '의사소통', '치매', '건망',
  '기분', '정서', '짜증', '불안', '행동', '표정',
  '방문', '보고', '관찰', '상태', '변화', '돌봄', '간병', '병원', '진료',
]

const OFF_TOPIC_HINTS = ['날씨', '뉴스', '주식', '축구', '야구', '드라마', '영화', '연예인', '정치', '게임', '유튜브']

export function isLikelyOffTopic(text: string): boolean {
  const t = text.trim()
  if (!t) return false
  if (CARE_KEYWORDS.some((k) => t.includes(k))) return false
  return OFF_TOPIC_HINTS.some((k) => t.includes(k))
}
